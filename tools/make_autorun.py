"""Pack an EPICYCLE SD-card autorun payload for the Akai MPC Sample.

Firmware 1.3.0.12: stock runs autorun/autorun.sh only if autorun.check equals
sha256(autorun.json + autorun.sh + fixed platform salt).

Firmware 1.4.x: salted check path is gone for community scripts. With Developer
Mode on, stock prompts to run top-of-card autorun.sh; we ship a bridge that
chains into autorun/autorun.sh.

This tool is original MIT code for EPICYCLE. The salt and check algorithm are
public platform facts also used by SampleBoot / MPC-600-S / sample-base docs.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import stat
import sys
import zipfile
from pathlib import Path

# Stock MPC Sample autorun.check salt (platform fact; do not invent a new one).
AUTORUN_SALT = b"f7bed1c9-7e90-4731-9194-c996666b4331"

LAUNCHER_SH = r'''#!/bin/sh
# EPICYCLE SD launcher — generated by tools/make_autorun.py (MIT).
# Follows SampleBoot OS-AUTHORS: resolve self from $0; card root from /proc/mounts.
set -eu
D=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
NAME="@NAME@"
PAYLOAD="$D/epicycle"

CARD=
best=0
while read -r _dev point _rest; do
  point=$(printf '%b' "$point")
  case "$D/" in
    "$point"/*)
      if [ ${#point} -gt "$best" ]; then
        CARD=$point
        best=${#point}
      fi
      ;;
  esac
done < /proc/mounts

# Card is often noexec; remount so nested helpers can run if needed.
if [ -n "${CARD:-}" ]; then
  mount -o remount,exec "$CARD" 2>/dev/null || true
fi

if command -v systemctl >/dev/null 2>&1 && systemctl is-active --quiet "$NAME.service"; then
  exit 0
fi

if [ ! -x "$PAYLOAD/$NAME" ]; then
  echo "epicycle: missing $PAYLOAD/$NAME" >&2
  exit 1
fi

cp "$PAYLOAD/$NAME" "/run/$NAME"
chmod 755 "/run/$NAME"

cat > "/run/$NAME-start.sh" <<'EOF'
#!/bin/sh
export MPC_APP_DIR="$1"
prog=$2
menu=${3:-}
has_systemd() { command -v systemctl >/dev/null 2>&1; }

# Solo-card boot: wait for stock, stop it, run us, then restore ac50.
if [ -z "$menu" ] && [ ! -f /run/mpc-boot-thingy.pid ] && has_systemd; then
  tries=0
  while [ "$tries" -lt 45 ]; do
    if systemctl is-active --quiet ac50.service; then
      systemctl stop ac50.service || true
      break
    fi
    tries=$((tries + 1))
    sleep 1
  done
fi

code=0
"/run/$prog" || code=$?

if [ ! -f /run/mpc-boot-thingy.pid ] && has_systemd; then
  systemctl start ac50.service || true
fi
exit "$code"
EOF
chmod 755 "/run/$NAME-start.sh"

# SampleBoot / boot-menu hand-off: run in place.
if [ -f /run/mpc-boot-thingy.pid ] || grep -q 'mpc-boot-autorun\.service' /proc/self/cgroup 2>/dev/null; then
  exec /bin/sh "/run/$NAME-start.sh" "$PAYLOAD" "$NAME" menu
fi

# Stock runner at power-on: queue and return so boot can finish.
systemd-run --unit="$NAME" --collect --no-block /bin/sh "/run/$NAME-start.sh" "$PAYLOAD" "$NAME"
'''


def die(msg: str, code: int = 1) -> None:
    print(f"make_autorun: {msg}", file=sys.stderr)
    raise SystemExit(code)


def write_bytes(path: Path, data: bytes, mode: int = 0o644) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    path.chmod(mode)


def build_autorun_json(name: str) -> bytes:
    doc = {
        "value0": {
            "scripts": [
                {
                    "path": "autorun.sh",
                    "askQuestion": False,
                    "message": f"Start {name}?",
                    "yesButtonText": "Start",
                    "noButtonText": "Cancel",
                }
            ],
            "files": [],
        }
    }
    return (json.dumps(doc, indent=2) + "\n").encode()


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--name", default="epicycle", help="binary / systemd unit name")
    ap.add_argument("--version", default="0.0.0", help="version string for zip name")
    ap.add_argument("--program", required=True, type=Path, help="aarch64 binary to ship")
    ap.add_argument("--outdir", required=True, type=Path, help="output directory")
    ap.add_argument(
        "--top-autorun",
        type=Path,
        default=None,
        help="1.4 bridge script copied to package root as autorun.sh",
    )
    ap.add_argument(
        "--extra",
        action="append",
        default=[],
        type=Path,
        help="extra file to copy into autorun/epicycle/ (repeatable)",
    )
    args = ap.parse_args()

    name = args.name
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]*", name) or name.startswith("autorun"):
        die(f"not a usable name: {name}")
    if not args.program.is_file():
        die(f"program not found: {args.program}")

    out = args.outdir.resolve()
    if out in (Path("/"), Path.cwd().resolve()):
        die(f"refusing to write into {out}")

    pkg_root = out / "package"
    if pkg_root.exists():
        shutil.rmtree(pkg_root)
    autorun = pkg_root / "autorun"
    payload = autorun / "epicycle"
    payload.mkdir(parents=True)

    js = build_autorun_json(name)
    sh = LAUNCHER_SH.replace("@NAME@", name).encode()
    check = hashlib.sha256(js + sh + AUTORUN_SALT).hexdigest().encode() + b"\n"

    write_bytes(autorun / "autorun.json", js)
    write_bytes(autorun / "autorun.sh", sh, 0o755)
    write_bytes(autorun / "autorun.check", check)

    dest_bin = payload / name
    shutil.copyfile(args.program, dest_bin)
    dest_bin.chmod(dest_bin.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)

    # SampleBoot menu name (optional asset).
    write_bytes(autorun / "sampleboot.txt", b"EPICYCLE\n")

    for extra in args.extra:
        if not extra.is_file():
            die(f"extra not found: {extra}")
        base = extra.name
        if base in ("autorun.sh", "autorun.json", "autorun.check", name):
            die(f"refusing to overwrite launcher with extra {base}")
        shutil.copyfile(extra, payload / base)

    # Firmware 1.4 top-of-card bridge.
    if args.top_autorun:
        if not args.top_autorun.is_file():
            die(f"top-autorun not found: {args.top_autorun}")
        top = args.top_autorun.read_bytes()
        write_bytes(pkg_root / "autorun.sh", top, 0o755)
    else:
        bridge = (
            b"#!/bin/sh\n"
            b"# EPICYCLE 1.4 top-level bridge - runs autorun/autorun.sh\n"
            b'exec /bin/sh "$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)/autorun/autorun.sh"\n'
        )
        write_bytes(pkg_root / "autorun.sh", bridge, 0o755)

    # Empty user-data skeleton (does not overwrite existing card data on install docs).
    data = pkg_root / "Epicycle"
    for sub in ("projects", "samples", "kits", "logs"):
        (data / sub).mkdir(parents=True)
    (data / "settings.json").write_text('{\n  "version": 1\n}\n', encoding="utf-8")
    (data / "README.txt").write_text(
        "EPICYCLE user data lives here. Safe to keep when replacing autorun/.\n",
        encoding="utf-8",
    )
    (data / "samples" / "README.txt").write_text(
        "Drop pad01.wav … pad16.wav (or 1.wav …) here. PCM WAV only.\n"
        "If empty, EPICYCLE uses a built-in demo tone bank.\n",
        encoding="utf-8",
    )

    zip_name = f"EPICYCLE-{args.version}.zip"
    zpath = out / zip_name
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as zf:
        for path in sorted(pkg_root.rglob("*")):
            if path.is_dir():
                continue
            rel = path.relative_to(pkg_root).as_posix()
            mode = 0o755 if path.stat().st_mode & stat.S_IXUSR else 0o644
            info = zipfile.ZipInfo(rel, date_time=(2026, 1, 1, 0, 0, 0))
            info.external_attr = (mode & 0xFFFF) << 16
            info.compress_type = zipfile.ZIP_DEFLATED
            zf.writestr(info, path.read_bytes())

    # Also leave an unpacked tree for inspection / direct copy.
    unpacked = out / "sd-root"
    if unpacked.exists():
        shutil.rmtree(unpacked)
    shutil.copytree(pkg_root, unpacked)

    sha = hashlib.sha256(zpath.read_bytes()).hexdigest()
    (out / "SHA256SUMS").write_text(f"{sha}  {zip_name}\n", encoding="utf-8")
    print(zpath)
    print(f"sha256 {sha}")
    print(f"unpacked {unpacked}")


if __name__ == "__main__":
    main()
